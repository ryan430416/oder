export function getLang() {
  const saved = storage.get(config.LANG_KEY, "zh");
  return LANGS.some((l) => l.id === saved) ? saved : "zh";
}

export function setLang(id) {
  storage.set(config.LANG_KEY, id);
}

export function t(key, vars = {}) {
  const lang = getLang();
  let text = dict[lang]?.[key] ?? dict.zh[key] ?? key;
  Object.entries(vars).forEach(([k, v]) => {
    text = text.replaceAll(`{${k}}`, String(v));
  });
  return text;
}

export function statusLabel(code) {
  return t("status_" + code) || code;
}

export function storeLabel(store) {
  if (!store) return "";
  return {
    name: t(`store.${store.store_id}.name`),
    desc: t(`store.${store.store_id}.desc`),
  };
}

export function productLabel(productId, fallback = "") {
  const name = t(`product.${productId}`);
  return name.startsWith("product.") ? fallback : name;
}

export function productDesc(productId, fallback = "") {
  const name = t(`product.${productId}.d`);
  return name.startsWith("product.") ? fallback : name;
}

export function categoryLabel(raw) {
  const key = CAT_KEY[raw];
  return key ? t(key) : raw;
}

export function applyI18n() {
  const meta = LANGS.find((l) => l.id === getLang()) || LANGS[0];
  document.documentElement.lang = meta.html;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
  });
  const titleEl = document.querySelector("title[data-i18n]");
  if (titleEl) document.title = t(titleEl.getAttribute("data-i18n"));
}

export function mountLangSwitch() {
  let host = document.querySelector(".js-lang");
  if (!host) {
    host = document.createElement("div");
    host.className = "js-lang";
    const actions = document.querySelector(".topbar-actions") || document.querySelector(".portal");
    if (actions) actions.prepend(host);
    else document.body.prepend(host);
  }
  const current = getLang();
  host.innerHTML = `<select class="lang-select" aria-label="${t("lang_aria")}">
    ${LANGS.map((l) => `<option value="${l.id}" ${l.id === current ? "selected" : ""}>${l.label}</option>`).join("")}
  </select>`;
  host.querySelector("select").addEventListener("change", (e) => {
    setLang(e.target.value);
    location.reload();
  });
}

export function initI18n() {
  applyI18n();
  mountLangSwitch();
}
