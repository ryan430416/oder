-- Canonical Auth-backed schema for a fresh Supabase project.
-- Product images must live in Storage. Never store Base64/Data URLs in tables.

create extension if not exists pgcrypto;

create table if not exists public.stores (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(trim(name)) between 1 and 80),
  description text not null default '' check (char_length(description) <= 500),
  image_url text,
  open_time time not null default '08:35',
  close_time time not null default '13:00',
  service_periods text[] not null default array['breakfast', 'lunch']::text[]
    check (
      cardinality(service_periods) > 0
      and service_periods <@ array['breakfast', 'lunch', 'afternoon_tea']::text[]
    ),
  status text not null default 'open' check (status in ('open', 'closed', 'disabled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '' check (char_length(display_name) <= 80),
  grade text not null default '' check (grade in ('', 'high_1', 'high_2', 'high_3')),
  role text not null default 'customer' check (role in ('customer', 'store', 'admin')),
  store_id uuid references public.stores(id) on delete set null,
  status text not null default 'active' check (status in ('active', 'disabled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((role = 'store' and store_id is not null) or role <> 'store')
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete restrict,
  name text not null check (char_length(trim(name)) between 1 and 100),
  category text not null default '其他' check (char_length(category) between 1 and 40),
  description text not null default '' check (char_length(description) <= 500),
  price numeric(12,2) not null check (price >= 0),
  image_path text check (
    image_path is null
    or (
      image_path !~ '^(data:|blob:|https?://)'
      and char_length(image_path) <= 500
    )
  ),
  -- Runtime signed URLs are generated by the client and are never persisted.
  image_url text check (image_url is null),
  status text not null default 'active' check (status in ('active', 'soldout', 'hidden')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create sequence if not exists public.order_number_seq;

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique default (
    'ORD-' || to_char(now() at time zone 'Asia/Taipei', 'YYYYMMDD') || '-' ||
    lpad(nextval('public.order_number_seq')::text, 6, '0')
  ),
  customer_id uuid not null references auth.users(id) on delete restrict,
  customer_name text not null check (char_length(trim(customer_name)) between 1 and 80),
  customer_grade text not null default '' check (customer_grade in ('', 'high_1', 'high_2', 'high_3')),
  store_id uuid not null references public.stores(id) on delete restrict,
  pickup_time timestamptz not null,
  payment_method text not null check (payment_method in ('cash', 'campus')),
  total numeric(12,2) not null check (total >= 0),
  status text not null default 'pending'
    check (status in ('pending', 'accepted', 'preparing', 'ready', 'completed', 'rejected', 'cancelled')),
  idempotency_key uuid not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (customer_id, idempotency_key)
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name_snapshot text not null,
  unit_price numeric(12,2) not null check (unit_price >= 0),
  quantity integer not null check (quantity between 1 and 99),
  subtotal numeric(12,2) not null check (subtotal >= 0)
);

create table if not exists public.notifications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete cascade,
  store_id uuid references public.stores(id) on delete cascade,
  order_id uuid references public.orders(id) on delete cascade,
  type text not null check (char_length(type) between 1 and 50),
  message text not null check (char_length(message) <= 500),
  is_read boolean not null default false,
  created_at timestamptz not null default now(),
  check (user_id is not null or store_id is not null)
);

create table if not exists public.reviews (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references auth.users(id) on delete cascade,
  store_id uuid not null references public.stores(id) on delete cascade,
  order_id uuid not null unique references public.orders(id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  comment text not null default '' check (char_length(comment) <= 500),
  hidden boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists products_store_status_idx on public.products(store_id, status);
create index if not exists orders_customer_created_idx on public.orders(customer_id, created_at desc);
create index if not exists orders_store_created_idx on public.orders(store_id, created_at desc);
create index if not exists notifications_user_created_idx on public.notifications(user_id, created_at desc);
create index if not exists notifications_store_created_idx on public.notifications(store_id, created_at desc);

