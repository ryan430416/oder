create or replace function public.is_service_pickup_time(p_periods text[], p_time time)
returns boolean language sql immutable set search_path = public as $$
  select
    p_time between '08:35'::time and '08:45'::time
    or p_time between '09:30'::time and '09:40'::time
    or p_time between '10:25'::time and '10:35'::time
    or p_time between '11:20'::time and '11:30'::time
    or p_time between '12:15'::time and '13:00'::time
    or p_time between '17:15'::time and '17:30'::time
    or p_time between '18:15'::time and '18:25'::time
$$;

create or replace function public.update_my_profile(p_display_name text, p_grade text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare v_profile public.profiles%rowtype;
begin
  if auth.uid() is null then return jsonb_build_object('ok', false, 'code', 'bad_login'); end if;
  if char_length(trim(coalesce(p_display_name, ''))) not between 1 and 80 then
    return jsonb_build_object('ok', false, 'code', 'need_name');
  end if;
  if coalesce(p_grade, '') not in ('high_1', 'high_2', 'high_3') then
    return jsonb_build_object('ok', false, 'code', 'invalid_grade');
  end if;
  update public.profiles
  set display_name = trim(p_display_name), grade = p_grade
  where id = auth.uid() and role = 'customer' and status = 'active'
  returning * into v_profile;
  if not found then return jsonb_build_object('ok', false, 'code', 'bad_login'); end if;
  return jsonb_build_object('ok', true, 'profile', to_jsonb(v_profile));
end
$$;

create or replace function public.pickup_is_within_order_window(p_pickup timestamptz)
returns boolean
language sql
stable
set search_path = public
as $$
  select
    p_pickup >= now() + interval '15 minutes'
    and (p_pickup at time zone 'Asia/Taipei')::date
        <= (timezone('Asia/Taipei', now()))::date + 1
$$;

create or replace function public.create_order(
  p_store_id uuid,
  p_customer_name text,
  p_pickup_time timestamptz,
  p_payment_method text,
  p_items jsonb,
  p_idempotency_key uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_profile public.profiles%rowtype;
  v_store public.stores%rowtype;
  v_order public.orders%rowtype;
  v_existing public.orders%rowtype;
  v_item jsonb;
  v_product public.products%rowtype;
  v_qty integer;
  v_total numeric(12,2) := 0;
begin
  if auth.uid() is null then
    return jsonb_build_object('ok', false, 'code', 'bad_login');
  end if;
  select * into v_profile from public.profiles
  where id = auth.uid() and role = 'customer' and status = 'active';
  if not found then return jsonb_build_object('ok', false, 'code', 'bad_login'); end if;
  if char_length(trim(coalesce(p_customer_name, ''))) not between 1 and 80 then
    return jsonb_build_object('ok', false, 'code', 'need_name');
  end if;

  select * into v_existing from public.orders
  where customer_id = auth.uid() and idempotency_key = p_idempotency_key;
  if found then
    return jsonb_build_object('ok', true, 'duplicate', true, 'order', to_jsonb(v_existing));
  end if;

  select * into v_store from public.stores where id = p_store_id and status = 'open' for update;
  if not found then return jsonb_build_object('ok', false, 'code', 'store_closed'); end if;
  if not public.pickup_is_within_order_window(p_pickup_time)
     or extract(minute from p_pickup_time)::integer % 5 <> 0
     or extract(second from p_pickup_time) <> 0
     or not public.is_service_pickup_time(
       v_store.service_periods,
       (p_pickup_time at time zone 'Asia/Taipei')::time
     ) then
    return jsonb_build_object('ok', false, 'code', 'invalid_pickup');
  end if;
  if p_payment_method not in ('cash', 'campus') then
    return jsonb_build_object('ok', false, 'code', 'invalid_payment');
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    return jsonb_build_object('ok', false, 'code', 'invalid_items');
  end if;

  for v_item in select * from jsonb_array_elements(p_items)
  loop
    begin
      v_qty := (v_item->>'quantity')::integer;
    exception when others then
      return jsonb_build_object('ok', false, 'code', 'invalid_items');
    end;
    select * into v_product from public.products
    where id = (v_item->>'product_id')::uuid
      and store_id = p_store_id and status = 'active'
    for update;
    if not found or v_qty not between 1 and 99 then
      return jsonb_build_object('ok', false, 'code', 'invalid_items');
    end if;
    v_total := v_total + (v_product.price * v_qty);
  end loop;

  update public.profiles
  set display_name = trim(p_customer_name)
  where id = auth.uid();

  insert into public.orders(
    customer_id, customer_name, customer_grade, store_id, pickup_time,
    payment_method, total, status, idempotency_key
  )
  values (
    auth.uid(), trim(p_customer_name), v_profile.grade, p_store_id, p_pickup_time,
    p_payment_method, v_total, 'pending', p_idempotency_key
  )
  returning * into v_order;

  for v_item in select * from jsonb_array_elements(p_items)
  loop
    v_qty := (v_item->>'quantity')::integer;
    select * into v_product from public.products where id = (v_item->>'product_id')::uuid;
    insert into public.order_items(
      order_id, product_id, product_name_snapshot, unit_price, quantity, subtotal
    )
    values (
      v_order.id, v_product.id, v_product.name, v_product.price, v_qty, v_product.price * v_qty
    );
  end loop;

  insert into public.notifications(store_id, order_id, type, message)
  values (p_store_id, v_order.id, 'new_order', '新訂單 ' || v_order.order_number);

  return jsonb_build_object('ok', true, 'order', to_jsonb(v_order));
exception
  when unique_violation then
    select * into v_existing from public.orders
    where customer_id = auth.uid() and idempotency_key = p_idempotency_key;
    return jsonb_build_object('ok', true, 'duplicate', true, 'order', to_jsonb(v_existing));
  when invalid_text_representation then
    return jsonb_build_object('ok', false, 'code', 'invalid_items');
end
$$;

create or replace function public.update_order_status(p_order_id uuid, p_next_status text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
  v_allowed boolean;
begin
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then return jsonb_build_object('ok', false, 'code', 'no_order'); end if;
  if not public.is_admin() and v_order.store_id is distinct from public.current_store_id() then
    return jsonb_build_object('ok', false, 'code', 'not_store');
  end if;
  v_allowed :=
    (v_order.status = 'pending' and p_next_status in ('accepted', 'rejected'))
    or (v_order.status = 'accepted' and p_next_status = 'preparing')
    or (v_order.status = 'preparing' and p_next_status = 'ready')
    or (v_order.status = 'ready' and p_next_status = 'completed');
  if not v_allowed then return jsonb_build_object('ok', false, 'code', 'invalid_status'); end if;

  update public.orders set status = p_next_status where id = p_order_id returning * into v_order;
  insert into public.notifications(user_id, store_id, order_id, type, message)
  values (
    v_order.customer_id, v_order.store_id, v_order.id, 'order_status',
    v_order.order_number || '：' || p_next_status
  );
  return jsonb_build_object('ok', true, 'order', to_jsonb(v_order));
end
$$;

create or replace function public.cancel_order(p_order_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
  v_staff boolean;
begin
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then return jsonb_build_object('ok', false, 'code', 'no_order'); end if;
  v_staff := public.is_admin() or v_order.store_id = public.current_store_id();
  if not v_staff and v_order.customer_id <> auth.uid() then
    return jsonb_build_object('ok', false, 'code', 'cannot_cancel');
  end if;
  if (not v_staff and v_order.status <> 'pending')
     or (v_staff and v_order.status not in ('pending', 'accepted', 'preparing')) then
    return jsonb_build_object('ok', false, 'code', 'cannot_cancel');
  end if;
  update public.orders set status = 'cancelled' where id = p_order_id returning * into v_order;
  return jsonb_build_object('ok', true, 'order', to_jsonb(v_order));
end
$$;

create or replace function public.delete_or_hide_product(p_product_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_product public.products%rowtype;
  v_has_orders boolean;
begin
  select * into v_product from public.products where id = p_product_id for update;
  if not found then return jsonb_build_object('ok', false, 'code', 'no_product'); end if;
  if not public.is_admin() and v_product.store_id is distinct from public.current_store_id() then
    return jsonb_build_object('ok', false, 'code', 'not_store');
  end if;
  select exists(select 1 from public.order_items where product_id = p_product_id) into v_has_orders;
  if v_has_orders then
    update public.products set status = 'hidden' where id = p_product_id returning * into v_product;
    return jsonb_build_object('ok', true, 'hidden', true, 'product', to_jsonb(v_product));
  end if;
  delete from public.products where id = p_product_id;
  return jsonb_build_object('ok', true, 'deleted', true, 'image_path', v_product.image_path);
end
$$;

create or replace function public.mark_notification_read(p_notification_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.notifications
  set is_read = true
  where id = p_notification_id
    and (
      public.is_admin()
      or user_id = auth.uid()
      or store_id = public.current_store_id()
    );
  if not found then return jsonb_build_object('ok', false, 'code', 'not_found'); end if;
  return jsonb_build_object('ok', true);
end
$$;

